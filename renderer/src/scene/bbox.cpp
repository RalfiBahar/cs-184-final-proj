bool BBox::intersect(const Ray& r, double& t0, double& t1) const {

  // TODO (Part 2.2):
  // Implement ray - bounding box intersection test
  // If the ray intersected the bouding box within the range given by
  // t0, t1, update t0 and t1 with the new intersection times.
    
    if (empty() || t0 > t1) return false;

    double enter = t0;
    double exit = t1;

    for (int axis = 0; axis < 3; ++axis) {
        const double origin = r.o[axis];
        const double direction = r.d[axis];

        if (direction == 0.0) {
            if (origin < min[axis] || origin > max[axis]) return false;
            continue;
        }

        double near_t = (min[axis] - origin) / direction;
        double far_t = (max[axis] - origin) / direction;
        if (near_t > far_t) std::swap(near_t, far_t);

        if (near_t > enter) enter = near_t;
        if (far_t < exit) exit = far_t;
        if (enter > exit) return false;
    }

    t0 = enter;
    t1 = exit;
    return true;
}

void BBox::draw(Color c, float alpha) const {

  glColor4f(c.r, c.g, c.b, alpha);

  // top
  glBegin(GL_LINE_STRIP);
  glVertex3d(max.x, max.y, max.z);
  glVertex3d(max.x, max.y, min.z);
  glVertex3d(min.x, max.y, min.z);
  glVertex3d(min.x, max.y, max.z);
  glVertex3d(max.x, max.y, max.z);
  glEnd();

  // bottom
  glBegin(GL_LINE_STRIP);
  glVertex3d(min.x, min.y, min.z);
  glVertex3d(min.x, min.y, max.z);
  glVertex3d(max.x, min.y, max.z);
  glVertex3d(max.x, min.y, min.z);
  glVertex3d(min.x, min.y, min.z);
  glEnd();

  // side
  glBegin(GL_LINES);
  glVertex3d(max.x, max.y, max.z);
  glVertex3d(max.x, min.y, max.z);
  glVertex3d(max.x, max.y, min.z);
  glVertex3d(max.x, min.y, min.z);
  glVertex3d(min.x, max.y, min.z);
  glVertex3d(min.x, min.y, min.z);
  glVertex3d(min.x, max.y, max.z);
  glVertex3d(min.x, min.y, max.z);
  glEnd();

}

